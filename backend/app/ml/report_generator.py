    def _generate_model_comparison_section(self, model_results: Dict[str, Any]) -> str:
        """Generate model comparison section"""
        
        models = model_results.get('models', {})
        task_type = model_results.get('task_type', 'classification')
        
        html = """
        <div class="section">
            <h2>⚖️ Model Performance Comparison</h2>
        """
        
        if models:
            html += """
            <table class="table">
                <thead>
                    <tr>
                        <th>Model</th>
                        <th>Status</th>
            """
            
            # Add metric columns based on task type
            if task_type == 'classification':
                html += "<th>Accuracy</th><th>F1-Score</th><th>Precision</th><th>Recall</th>"
            else:
                html += "<th>RMSE</th><th>MAE</th><th>R²</th>"
            
            html += "</tr></thead><tbody>"
            
            for model_name, model_data in models.items():
                status = model_data.get('status', 'unknown')
                status_color = '#27ae60' if status == 'completed' else '#e74c3c'
                
                html += f"""
                    <tr>
                        <td><strong>{model_name}</strong></td>
                        <td style="color: {status_color};">{status.title()}</td>
                """
                
                if status == 'completed':
                    metrics = model_data.get('metrics', {}).get('test', {})
                    
                    if task_type == 'classification':
                        html += f"""
                            <td>{metrics.get('accuracy', 0):.4f}</td>
                            <td>{metrics.get('f1_score', 0):.4f}</td>
                            <td>{metrics.get('precision', 0):.4f}</td>
                            <td>{metrics.get('recall', 0):.4f}</td>
                        """
                    else:
                        html += f"""
                            <td>{metrics.get('rmse', 0):.4f}</td>
                            <td>{metrics.get('mae', 0):.4f}</td>
                            <td>{metrics.get('r2', 0):.4f}</td>
                        """
                else:
                    # Fill with N/A for failed models
                    n_metrics = 4 if task_type == 'classification' else 3
                    html += "<td>N/A</td>" * n_metrics
                
                html += "</tr>"
            
            html += "</tbody></table>"
        
        html += "</div>"
        return html
    
    def _generate_best_model_section(self, model_results: Dict[str, Any]) -> str:
        """Generate best model details section"""
        
        best_model_name = model_results.get('best_model')
        
        html = """
        <div class="section">
            <h2>🏆 Best Model</h2>
        """
        
        if best_model_name:
            models = model_results.get('models', {})
            best_model_data = models.get(best_model_name, {})
            
            html += f"""
            <div class="success">
                <h3>{best_model_name}</h3>
                <p><strong>Status:</strong> {best_model_data.get('status', 'Unknown').title()}</p>
            """
            
            if best_model_data.get('status') == 'completed':
                metrics = best_model_data.get('metrics', {})
                test_metrics = metrics.get('test', {})
                train_metrics = metrics.get('train', {})
                
                html += "<h4>Performance Metrics:</h4><ul>"
                
                task_type = model_results.get('task_type', 'classification')
                if task_type == 'classification':
                    html += f"""
                        <li><strong>Test Accuracy:</strong> {test_metrics.get('accuracy', 0):.4f}</li>
                        <li><strong>Test F1-Score:</strong> {test_metrics.get('f1_score', 0):.4f}</li>
                        <li><strong>Training Accuracy:</strong> {train_metrics.get('accuracy', 0):.4f}</li>
                    """
                else:
                    html += f"""
                        <li><strong>Test RMSE:</strong> {test_metrics.get('rmse', 0):.4f}</li>
                        <li><strong>Test R²:</strong> {test_metrics.get('r2', 0):.4f}</li>
                        <li><strong>Training RMSE:</strong> {train_metrics.get('rmse', 0):.4f}</li>
                    """
                
                html += "</ul>"
                
                # Check for overfitting
                if task_type == 'classification':
                    train_acc = train_metrics.get('accuracy', 0)
                    test_acc = test_metrics.get('accuracy', 0)
                    if train_acc - test_acc > 0.1:
                        html += '<div class="warning">⚠️ Potential overfitting detected (training accuracy significantly higher than test accuracy)</div>'
                
            html += "</div>"
        else:
            html += '<div class="error">No best model identified. Check training results.</div>'
        
        html += "</div>"
        return html
    
