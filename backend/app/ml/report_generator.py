    async def generate_eda_report(self, df: pd.DataFrame, eda_results: Dict[str, Any]) -> str:
        """Generate comprehensive EDA HTML report"""
        
        try:
            html_content = f"""
            <!DOCTYPE html>
            <html lang="en">
            <head>
                <meta charset="UTF-8">
                <meta name="viewport" content="width=device-width, initial-scale=1.0">
                <title>EDA Report - {eda_results.get('dataset_id', 'Dataset')}</title>
                {self.template_style}
            </head>
            <body>
                <div class="container">
                    <div class="header">
                        <h1>📊 Exploratory Data Analysis Report</h1>
                        <p>Dataset: <strong>{eda_results.get('dataset_id', 'Unknown')}</strong></p>
                        <p>Generated on: {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}</p>
                    </div>
            """
            
            # Dataset Overview Section
            html_content += self._generate_overview_section(df, eda_results)
            
            # Data Quality Section
            html_content += self._generate_data_quality_section(eda_results)
            
            # Statistical Analysis Section
            html_content += self._generate_statistical_section(eda_results)
            
            # Relationships Section
            html_content += self._generate_relationships_section(eda_results)
            
            # Recommendations Section
            html_content += self._generate_recommendations_section(eda_results)
            
            html_content += f"""
                    <div class="timestamp">
                        Report generated by AI EDA Platform
                    </div>
                </div>
            </body>
            </html>
            """
            
            return html_content
            
        except Exception as e:
            logger.error(f"Failed to generate EDA report: {str(e)}")
            return self._generate_error_report("EDA Report Generation Failed", str(e))
    
